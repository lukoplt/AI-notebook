#!/usr/bin/env python3
"""Write <work>/Versions.props with package versions taken from the App's committed NuGet lock files,
so the macOS type-check uses exactly the WinAppSDK projections the Windows build resolves."""
import json, os, sys

repo, work = sys.argv[1], sys.argv[2]


def direct_and_transitive(lock_path):
    deps = {}
    with open(lock_path, encoding='utf-8') as f:
        for tfm, packages in json.load(f)['dependencies'].items():
            if '/' in tfm:  # runtime-specific graph repeats the same packages
                continue
            for name, info in packages.items():
                deps[name] = info.get('resolved')
    return deps


app = direct_and_transitive(os.path.join(repo, 'windows/src/AINotebook.App/packages.lock.json'))
tests = direct_and_transitive(os.path.join(repo, 'windows/tests/AINotebook.App.Tests/packages.lock.json'))
props = {
    'WtcWinUIVersion': app['Microsoft.WindowsAppSDK.WinUI'],
    'WtcFoundationVersion': app['Microsoft.WindowsAppSDK.Foundation'],
    'WtcInteractiveExperiencesVersion': app['Microsoft.WindowsAppSDK.InteractiveExperiences'],
    'WtcWebView2Version': app['Microsoft.Web.WebView2'],
    'WtcMvvmVersion': app['CommunityToolkit.Mvvm'],
    'WtcDependencyInjectionVersion': app['Microsoft.Extensions.DependencyInjection'],
    'WtcTestSdkVersion': tests['Microsoft.NET.Test.Sdk'],
    'WtcXunitVersion': tests['xunit'],
    'WtcXunitRunnerVersion': tests['xunit.runner.visualstudio'],
}
os.makedirs(work, exist_ok=True)
lines = ['<Project>', '  <!-- Generated by tools/windows-typecheck/versions.py from the App lock files. -->', '  <PropertyGroup>']
lines += [f'    <{k}>{v}</{k}>' for k, v in props.items()]
lines += ['  </PropertyGroup>', '</Project>', '']
with open(os.path.join(work, 'Versions.props'), 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines))
