#!/usr/bin/env python3
"""embedding-raw-format-v2 reference: task prefixes and a path header for raw embedding sessions.

Raw (non-catalog) sessions embedded text verbatim (formats `legacy` and `1`). Models such as
nomic-embed-text are trained with task prefixes and lose much of their quality without them.
Format `2` adds the model family's query/document prefixes and, for documents, a one-line path
header. Normative text: docs/contracts/embedding-raw-format-v2.md. Swift
`RawEmbeddingFormat` and C# `RawEmbeddingFormat` must reproduce every expected input exactly.
Standard library only.
"""

import argparse
import re
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = 'Tests/fixtures/contracts/embedding-raw-format-v2.json'
CURRENT = '2'
HEADER_MAX = 200  # scalars of the path line before the newline


def family(model):
    """ASCII-lowercased model name without surrounding ASCII whitespace, registry namespace and tag."""
    name = ''.join(chr(ord(c) + 32) if 'A' <= c <= 'Z' else c for c in model.strip(' \t\n\v\f\r'))
    name = name.rsplit('/', 1)[-1]
    return name.split(':', 1)[0]


def prefixes(model):
    name = family(model)
    if name.startswith('nomic-embed-text'):
        return 'search_query: ', 'search_document: '
    if 'e5' in name.replace('_', '-').split('-') and 'instruct' not in name:
        return 'query: ', 'passage: '
    return '', ''


def header(rel_path, title):
    line = rel_path if rel_path else title
    # Runs of ASCII whitespace (space, \t, \n, \v, \f, \r) become one space; ends are trimmed.
    words = [w for w in re.split('[ \t\n\v\f\r]+', line) if w]
    line = ' '.join(words)
    return line[:HEADER_MAX] + '\n' if line else ''


def query(text, model, fmt):
    return prefixes(model)[0] + text if fmt == '2' else text


def document(text, model, fmt, rel_path=None, title=''):
    return prefixes(model)[1] + header(rel_path, title) + text if fmt == '2' else text


CASES = [
    ('nomic-query', 'nomic-embed-text', 'query', 'Kdy končí smlouva?', None, ''),
    ('nomic-tag-document', 'nomic-embed-text:latest', 'document', 'A1: Faktura', 'Klient/2026/Nabidky/x.xlsx', 'x.xlsx'),
    ('nomic-v2-moe-document', 'nomic-embed-text-v2-moe', 'document', 'text', 'a/b.pdf', 'b.pdf'),
    ('namespace-nomic', 'library/Nomic-Embed-Text:v1.5', 'query', 'q', None, ''),
    ('e5-query', 'jeffh/intfloat-multilingual-e5-large:f16', 'query', 'q', None, ''),
    ('e5-document-loose', 'multilingual-e5-base', 'document', 'p', None, 'Poznámky.md'),
    ('e5-instruct-no-prefix', 'multilingual-e5-large-instruct', 'document', 'p', 'a.txt', 'a.txt'),
    ('bge-m3-header-only', 'bge-m3', 'document', 'p', 'Složka/Soubor s  mezerami\tA.docx', 'A.docx'),
    ('nbsp-kept', 'bge-m3', 'document', 'p', 'a\u00a0b.txt', 'a\u00a0b.txt'),
    ('bge-m3-query-unchanged', 'bge-m3', 'query', 'q', None, ''),
    ('long-header-cut', 'bge-m3', 'document', 'p', '/'.join(['d' * 30] * 10) + '/f.txt', 'f.txt'),
    ('format-1-unchanged', 'nomic-embed-text', 'document', 'p', 'a.txt', 'a.txt'),
    ('legacy-unchanged', 'nomic-embed-text', 'query', 'q', None, ''),
]


def build():
    cases = []
    for name, model, purpose, text, rel_path, title in CASES:
        fmt = '1' if name == 'format-1-unchanged' else 'legacy' if name == 'legacy-unchanged' else CURRENT
        expected = query(text, model, fmt) if purpose == 'query' else document(text, model, fmt, rel_path, title)
        cases.append({'name': name, 'model': model, 'format': fmt, 'purpose': purpose, 'text': text,
                      'relPath': rel_path, 'title': title, 'expected': expected})
    return {'contract': 'embedding-raw-format', 'version': 2, 'current': CURRENT, 'headerMaxScalars': HEADER_MAX,
            'cases': cases}


def render(fixture):
    return (json.dumps(fixture, ensure_ascii=False, sort_keys=True, indent=2, allow_nan=False) + '\n').encode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Compare generated bytes without writing.')
    args = parser.parse_args()
    path = ROOT / OUTPUT
    data = render(build())
    if args.check:
        if not path.is_file() or path.read_bytes() != data:
            print('out of date: ' + OUTPUT)
            return 1
        print('ok')
        return 0
    path.write_bytes(data)
    print('wrote ' + OUTPUT)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
